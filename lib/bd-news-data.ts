export function getBdNewsById(id: string) {
  return BD_NEWS_ARTICLES.find((item) => item.id === id)
}

export function getBdNewsByKind(kind: BdNewsKind) {
  return BD_NEWS_ARTICLES.filter((item) => item.kind === kind)
}

export function getBdPrevNext(id: string) {
  const index = BD_NEWS_ARTICLES.findIndex((item) => item.id === id)
  if (index === -1) return { prev: undefined, next: undefined }

  return {
    prev: index > 0 ? BD_NEWS_ARTICLES[index - 1] : undefined,
    next: index < BD_NEWS_ARTICLES.length - 1 ? BD_NEWS_ARTICLES[index + 1] : undefined,
  }
}
